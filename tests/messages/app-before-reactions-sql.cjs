// The new AURA code against a Supabase project where aura-messages-reactions.sql hasn't been run yet.
process.env.NO_REACTIONS_SQL = "1";
const path = require("path");
const { createWorld, USERS } = require("./harness.cjs");
let failed = 0;
const check = (name, ok, extra) => { if (!ok) failed++; console.log((ok ? "  ok    " : "  FAIL  ") + name + (ok ? "" : "  " + JSON.stringify(extra))); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const w = await createWorld(path.resolve(process.argv[2]));
  const A = w.login("A"), B = w.login("B");
  const ok = async (p) => { const r = await p; if (!r.success) throw new Error("call failed: " + r.error); return r.data; };
  await ok(A.call("start")); await ok(B.call("start")); await sleep(80);
  check("messages are still live", A.events.some((e) => e.type === "live" && e.connected === true) && !A.events.some((e) => e.type === "live" && e.connected === false), A.events);
  await ok(A.call("requestFriend", USERS.B.id)); await ok(B.call("requestFriend", USERS.A.id));
  const AB = await ok(A.call("openConversation", USERS.B.id));
  const m = await ok(A.call("sendMessage", AB, "hello")); await sleep(60);
  check("text still sends and arrives", m.content === "hello" && B.events.some((e) => e.type === "message" && e.message.content === "hello"));
  let t = await A.call("getMessages", AB);
  check("the history loads, with no likes on anything", t.success && t.data.messages.length === 1 && JSON.stringify(t.data.messages[0].reactions) === "[]", t);
  t = await A.call("getMessages", AB);
  check("and loads again", t.success && t.data.messages.length === 1);
  const SETUP = "Likes and dislikes aren't set up in Supabase yet. Run aura-messages-reactions.sql first.";
  const tried = await B.call("react", m.id, "like");
  check("liking says exactly what to do", tried.success === false && tried.error === SETUP, tried);
  check("taking one back says the same", (await B.call("react", m.id, null)).error === SETUP);
  check("the friend's AURA heard nothing about a like", !A.events.some((e) => e.type === "reaction"));
  check("deleting a message still works", (await ok(A.call("deleteMessage", m.id))) === true);
  check("calls still ring", !!(await ok(A.call("startCall", USERS.B.id))).id && (await sleep(80), B.events.some((e) => e.type === "call")));
  console.log(failed ? "\n" + failed + " FAILED" : "\nall passed");
  process.exit(failed ? 1 : 0);
})().catch((e) => { console.error("TEST CRASHED:", e); process.exit(2); });
