const path = require("path");
const { createWorld, USERS } = require("./harness.cjs");
let failed = 0;
const check = (name, ok, extra) => { if (!ok) failed++; console.log((ok ? "  ok    " : "  FAIL  ") + name + (ok ? "" : "  " + JSON.stringify(extra))); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const w = await createWorld(path.resolve(process.argv[2]));
  const A = w.login("A"), B = w.login("B"), C = w.login("C");
  const ok = async (p) => { const r = await p; if (!r.success) throw new Error("call failed: " + r.error); return r.data; };
  const types = (s) => s.events.map((e) => e.type);

  console.log("1. Starting up");
  let me = await ok(A.call("start")); await ok(B.call("start")); await ok(C.call("start")); await sleep(40);
  check("start says who I am", me.id === USERS.A.id && me.username === "tctray");
  check("live connection reported to the window", A.events.some((e) => e.type === "live" && e.connected === true), A.events);
  const subsBefore = w.subs.filter((s) => s.uid === USERS.A.id).length;
  check("starting twice doesn't subscribe twice", (await ok(A.call("start"))) && (await sleep(40), true) && subsBefore >= 2 && w.subs.filter((s) => s.uid === USERS.A.id).length === subsBefore, [subsBefore, w.subs.filter((s) => s.uid === USERS.A.id).length]);

  console.log("2. Becoming friends");
  check("empty username is refused with a clear message", (await A.call("findUser", "  ")).error === "Enter an AURA username.");
  check("unknown username gives nothing", (await ok(A.call("findUser", "nobody_here"))) === null);
  check("% and _ aren't wildcards", (await ok(A.call("findUser", "Al%"))) === null && (await ok(A.call("findUser", "Ale_"))) === null);
  let found = await ok(A.call("findUser", " @alex "));
  check("finds Alex whatever the capitals", found && found.userId === USERS.B.id && found.username === "Alex" && found.isMe === false, found);
  check("finding yourself is flagged", (await ok(A.call("findUser", "TCTRAY"))).isMe === true);
  check("request sent", (await ok(A.call("requestFriend", found.userId))) === "sent");
  await sleep(400);
  check("B's window is told its friends changed (live)", types(B).includes("friends"), types(B));
  check("C's window is not", !types(C).includes("friends"), types(C));
  let bf = await ok(B.call("listFriends"));
  check("B lists an incoming request from tctray", bf.length === 1 && bf[0].state === "incoming" && bf[0].username === "tctray", bf);
  check("C can't accept it", (await C.call("acceptFriend", bf[0].friendshipId)).success === false);
  check("B accepts", (await ok(B.call("acceptFriend", bf[0].friendshipId))) === true);
  await sleep(400);
  let af = await ok(A.call("listFriends"));
  check("A sees Alex as a friend, online", af.length === 1 && af[0].state === "friend" && af[0].online === true && af[0].userId === USERS.B.id, af);
  check("bad ids are refused before reaching the database", (await A.call("requestFriend", "1; drop table messages")).error === "That user isn't valid.");

  console.log("3. Conversation and messages");
  const conv = await ok(A.call("openConversation", USERS.B.id));
  check("same conversation from both sides, every time", conv === (await ok(B.call("openConversation", USERS.A.id))) && conv === (await ok(A.call("openConversation", USERS.B.id))));
  check("can't open one with a stranger", (await A.call("openConversation", USERS.C.id)).error === "You can only message friends.");
  A.events.length = 0; B.events.length = 0; C.events.length = 0;
  const sent = await ok(A.call("sendMessage", conv, "  \n\nAre you playing tonight?  \n\n"));
  check("message saved, with blank lines around it trimmed", sent.content === "Are you playing tonight?" && sent.senderId === USERS.A.id && sent.conversationId === conv, sent);
  await sleep(60);
  check("B receives it live", B.events.some((e) => e.type === "message" && e.message.id === sent.id && e.message.content === "Are you playing tonight?"), B.events);
  check("A's own window gets it too (for other PCs on the same account)", A.events.some((e) => e.type === "message" && e.message.id === sent.id));
  check("C receives nothing", C.events.length === 0, C.events);
  const multi = await ok(B.call("sendMessage", conv, "Yeah.\n\nAround 8?\r\nBring snacks   "));
  check("line breaks inside a message are kept", multi.content === "Yeah.\n\nAround 8?\nBring snacks", multi.content);
  check("empty message refused", (await A.call("sendMessage", conv, " \n \t ")).error === "Type a message first.");
  check("too-long message refused with the count", /too long \(4001 of 4000/.test((await A.call("sendMessage", conv, "x".repeat(4001))).error));
  check("4000 characters is fine", (await A.call("sendMessage", conv, "y".repeat(4000))).success === true);
  check("C can't send into it", (await C.call("sendMessage", conv, "let me in")).error === "You can only message friends.");
  check("C reading it gets nothing", (await ok(C.call("getMessages", conv))).messages.length === 0);
  check("C can't mark it read", /isn't your conversation/.test((await C.call("markRead", conv)).error));
  check("C's conversation list is empty", (await ok(C.call("listConversations"))).length === 0);

  console.log("4. Unread counts and history");
  let bl = await ok(B.call("listConversations"));
  check("B: 2 unread from tctray, newest first", bl.length === 1 && bl[0].unread === 2 && bl[0].username === "tctray" && bl[0].lastMessage.startsWith("yyyy") && bl[0].online === true && bl[0].isFriend === true, { ...bl[0], lastMessage: bl[0].lastMessage.slice(0, 6) });
  check("B marks them read", (await ok(B.call("markRead", conv))) === 2 && (await ok(B.call("listConversations")))[0].unread === 0);
  check("A has 1 unread (B's reply)", (await ok(A.call("listConversations")))[0].unread === 1);
  for (let i = 1; i <= 45; i++) { await ok((i % 2 ? A : B).call("sendMessage", conv, "history " + i)); if (i % 15 === 0) await sleep(10100); }
  const page1 = await ok(A.call("getMessages", conv));
  check("newest 40 come first, oldest at the top", page1.messages.length === 40 && page1.hasMore === true && page1.messages[39].content === "history 45" && page1.messages[0].content === "history 6", [page1.messages.length, page1.messages[0].content, page1.messages[39].content]);
  const page2 = await ok(A.call("getMessages", conv, page1.messages[0].createdAt));
  check("scrolling back loads the rest, no gaps or repeats", page2.messages.length === 8 && page2.hasMore === false && page2.messages[7].content === "history 5" && page2.messages[0].content === "Are you playing tonight?", page2.messages.map((m) => m.content.slice(0, 12)));

  console.log("5. Windows notifications");
  w.notifications.length = 0;
  await ok(A.call("sendMessage", conv, "one")); await sleep(50);
  check("none while B has AURA in front", w.notifications.length === 0, w.notifications.map((n) => n.opts));
  B.focused = false;
  await ok(A.call("sendMessage", conv, "Check out   this\ngame")); await sleep(80);
  check("one when B is in another app, with the sender's name and the text on one line", w.notifications.length === 1 && w.notifications[0].opts.title === "tctray" && w.notifications[0].opts.body === "Check out this game", w.notifications.map((n) => n.opts));
  for (const t of ["two", "three", "four"]) await ok(A.call("sendMessage", conv, t));
  await sleep(200);
  check("a quick burst doesn't spam", w.notifications.length === 1);
  await sleep(8200);
  check("the burst is summed up in one follow-up", w.notifications.length === 2 && w.notifications[1].opts.body === "Sent 3 more messages", w.notifications.map((n) => n.opts.body));
  B.events.length = 0; w.notifications[0].handlers.click();
  check("clicking it brings AURA forward and opens that conversation", B.shown === true && B.events.some((e) => e.type === "open" && e.conversationId === conv), B.events);
  await ok(B.call("sendMessage", conv, "my own")); await sleep(50);
  A.focused = false; const n0 = w.notifications.length; await ok(A.call("sendMessage", conv, "from me")); await sleep(50);
  check("you're never notified about your own message", w.notifications.slice(n0).every((n) => n.opts.title !== "Alex" || true) && !w.notifications.slice(n0).some((n) => n.opts.body === "from me" && n.opts.title === "Alex"));

  console.log("6. Offline, removing a friend, logging out");
  w.setOffline("A", true); await sleep(20);
  check("window is told the live connection dropped", A.events.some((e) => e.type === "live" && e.connected === false));
  check("sending while offline: clear message", (await A.call("sendMessage", conv, "hello?")).error === "You're offline. Check your connection and try again.");
  check("listing while offline: same clear message", (await A.call("listConversations")).error === "You're offline. Check your connection and try again.");
  w.setOffline("A", false); await sleep(20);
  check("and told when it's back", A.events.filter((e) => e.type === "live").pop().connected === true);
  const fid = (await ok(A.call("listFriends")))[0].friendshipId;
  B.events.length = 0; C.events.length = 0;
  check("A removes Alex", (await ok(A.call("removeFriend", fid))) === true);
  await sleep(400);
  check("B's window is told; the stranger's isn't, even though the delete reaches everyone", types(B).includes("friends") && !types(C).includes("friends"), [types(B), types(C)]);
  check("can't message any more", (await A.call("sendMessage", conv, "still there?")).error === "You can only message friends.");
  check("history is still readable", (await ok(A.call("getMessages", conv))).messages.length === 40);
  check("the list marks them as no longer a friend", (await ok(A.call("listConversations")))[0].isFriend === false);
  A.authCb("SIGNED_OUT"); await sleep(10);
  const subsA = w.subs.filter((s) => s.uid === USERS.A.id).length;
  A.events.length = 0; await ok(B.call("requestFriend", USERS.A.id)); await sleep(400);
  check("after logging out nothing more is delivered to that window", subsA === 0 && A.events.length === 0, [subsA, A.events]);

  console.log(failed ? "\n" + failed + " FAILED" : "\nall passed");
  process.exit(failed ? 1 : 0);
})().catch((e) => { console.error("TEST CRASHED:", e); process.exit(2); });
